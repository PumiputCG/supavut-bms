<?php

namespace App\Support;

/**
 * ลิงก์ที่ "ออกไปนอกระบบ" — อีเมล · QR · อะไรก็ตามที่คนจะเปิดจากเครื่องอื่น
 *
 * 🔴 ห้ามสร้างจาก APP_URL เด็ดขาด (กติกาเดิม DECISIONS 50.4 · บั๊กจริง 2026-09-18)
 *    APP_URL ของเครื่อง dev คือ http://localhost ซึ่งแปลว่า "เครื่องที่กำลังเปิดลิงก์นั้นอยู่"
 *    ลิงก์แบบนั้นเปิดได้เฉพาะบนเครื่องที่รันระบบเอง — มือถือของผู้รับเมลเปิดไม่ได้เลย
 *    และห้ามใส่พาธลง APP_URL แทน เพราะเทสต์จะพังทั้งชุด (บทเรียน 2026-09-15)
 *    → ยืมที่อยู่ฐานตัวเดียวกับ QR (`BMS_QR_BASE_URL`) ซึ่งตั้งเป็นที่อยู่จริงของเซิร์ฟไว้แล้ว
 *
 * 🔴 ที่อยู่นั้นอยู่ในวงแลน (192.168.7.x) เปิดจากเน็ตมือถือไม่ได้
 *    สิ่งที่ส่งออกไปจึงต้องอ่านรู้เรื่องโดยไม่ต้องกดลิงก์เสมอ
 */
final class OutboundLink
{
    /**
     * ที่อยู่เต็มของ route หนึ่ง — คืน null เมื่อสร้างไม่ได้
     *
     * ผู้เรียกต้องรับมือกับ null เองโดยไม่ใส่ลิงก์ ไม่ใช่โยน error ใส่ผู้ใช้
     */
    public static function route(?string $name, ?string $param = null): ?string
    {
        if ($name === null || $name === '') {
            return null;
        }

        try {
            // เอาเฉพาะ "พาธ" แล้วค่อยต่อกับฐานที่ตั้งไว้ — ไม่งั้นโฮสต์ของ APP_URL จะติดมาด้วย
            $path = route($name, $param, false);
        } catch (\Throwable) {
            return null;
        }

        $base = rtrim((string) config('bms.qr_base'), '/');

        return $base === '' ? url($path) : $base.$path;
    }
}
