       เขียน @json([...]) เป็นอาร์เรย์หลายบรรทัดแล้ว Blade อ่านวงเล็บไม่ครบ
       (ตรวจจริง 2026-09-17: มันตัดคีย์สุดท้ายทิ้งแล้วปิดวงเล็บเอง จนหน้าเป็น 500 ทั้งระบบ)
