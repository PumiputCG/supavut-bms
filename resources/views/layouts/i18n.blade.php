    var STORAGE_KEY = 'bms_lang';

    // path ของธง — ให้ Blade เป็นคนสร้าง URL จะได้ถูกทั้งตอน dev และตอนอยู่ใต้ซับโฟลเดอร์บนเซิร์ฟ
    var FLAG_TH = '{{ asset('img/flag-th.webp') }}';
    var FLAG_EN = '{{ asset('img/flag-en.png') }}';

    function currentLang() {
      try {
        var saved = window.localStorage.getItem(STORAGE_KEY);
        if (saved === 'th' || saved === 'en') return saved;
      } catch (e) { /* โหมดส่วนตัว / บล็อก storage — ถอยไปใช้ค่าเริ่มต้น */ }
      return 'th';
    }

    function apply(lang) {
      var map = DICT[lang] || DICT.th;
      var root = document.documentElement;
      root.setAttribute('lang', lang === 'en' ? 'en' : 'th');
      root.setAttribute('data-lang', lang);

      document.querySelectorAll('[data-i18n]').forEach(function (el) {
        var v = map[el.getAttribute('data-i18n')];
        if (v !== undefined) el.textContent = v;
      });
      [['data-i18n-placeholder', 'placeholder'], ['data-i18n-aria', 'aria-label'], ['data-i18n-title', 'title']]
        .forEach(function (pair) {
          document.querySelectorAll('[' + pair[0] + ']').forEach(function (el) {
            var v = map[el.getAttribute(pair[0])];
            if (v !== undefined) el.setAttribute(pair[1], v);
          });
        });

      // ข้อความที่มาจากฐานข้อมูล — ไม่มีอังกฤษให้ถอยไปใช้ไทย ห้ามปล่อยว่าง
      document.querySelectorAll('[data-loc-th]').forEach(function (el) {
        var th = el.getAttribute('data-loc-th') || '';
        var en = el.getAttribute('data-loc-en') || '';
        el.textContent = lang === 'en' ? (en || th) : (th || en);
      });

      /*
        tooltip ที่มาจากฐานข้อมูล (เพิ่ม 2026-09-17)
        🔴 แยกจาก data-loc-th เพราะตัวนั้นเขียนทับ textContent — ใส่กับป้ายโค้ด "NM" แล้วโค้ดจะกลายเป็นชื่อกลุ่ม
      */
      document.querySelectorAll('[data-loc-title-th]').forEach(function (el) {
        var th = el.getAttribute('data-loc-title-th') || '';
        var en = el.getAttribute('data-loc-title-en') || '';
        el.setAttribute('title', lang === 'en' ? (en || th) : (th || en));
      });

      // ปุ่มหลักโชว์ธง + ชื่อภาษาที่เลือกอยู่ (ตามที่เจ้าของสั่งให้ใช้ธงแทนไอคอนลูกโลก)
      document.querySelectorAll('[data-lang-label]').forEach(function (el) {
        el.textContent = lang === 'en' ? map['common.langEn'] : map['common.langTh'];
      });
      document.querySelectorAll('[data-lang-flag]').forEach(function (img) {
        img.src = lang === 'en' ? FLAG_EN : FLAG_TH;
      });
      document.querySelectorAll('[data-lang-set]').forEach(function (el) {
        el.setAttribute('aria-current', el.getAttribute('data-lang-set') === lang ? 'true' : 'false');
      });

      document.dispatchEvent(new CustomEvent('bms:languagechange', { detail: { lang: lang } }));
    }

    function setLang(lang) {
      try { window.localStorage.setItem(STORAGE_KEY, lang); } catch (e) { /* เก็บไม่ได้ก็ยังสลับภาษาได้ในหน้านี้ */ }
      apply(lang);
    }

    // เปิดเผยให้หน้าอื่นเรียกใช้ได้ (เช่น ข้อความที่ JS สร้างตอนรัน)
    window.BMS = window.BMS || {};
    window.BMS.dict = DICT;
    window.BMS.lang = currentLang;
    window.BMS.setLang = setLang;
    // หน้าที่สร้าง DOM ขึ้นมาเองตอนรัน (เช่น ผลค้นหา) เรียกอันนี้เพื่อให้คำแปลลงไปด้วย
    window.BMS.refresh = function () { apply(currentLang()); };
    window.BMS.t = function (key, fallback) {
      var map = DICT[currentLang()] || DICT.th;
      return map[key] !== undefined ? map[key] : (fallback || key);
    };

    document.addEventListener('DOMContentLoaded', function () {
      apply(currentLang());

      document.querySelectorAll('[data-lang-toggle]').forEach(function (btn) {
        var menu = btn.parentElement.querySelector('[data-lang-menu]');
        if (!menu) return;
        menu.hidden = true;
        btn.addEventListener('click', function (e) {
          e.stopPropagation();
          // เปิดได้ทีละแผง — ปิดกระดิ่ง/ช่วยเหลือ/เมนูผู้ใช้ ที่ค้างอยู่ก่อน
          // เช็คก่อนเรียกเพราะหน้าล็อกอินไม่มีโครงหน้าที่นิยามตัวนี้ไว้
          if (window.BMS && window.BMS.closePopovers) { window.BMS.closePopovers(menu); }
          menu.hidden = !menu.hidden;
        });
      });
      document.querySelectorAll('[data-lang-set]').forEach(function (btn) {
        btn.addEventListener('click', function () {
          setLang(btn.getAttribute('data-lang-set'));
          var menu = btn.closest('[data-lang-menu]');
          if (menu) menu.hidden = true;
        });
      });
      document.addEventListener('click', function () {
        document.querySelectorAll('[data-lang-menu]').forEach(function (m) { m.hidden = true; });
      });
    });
  })();
</script>
